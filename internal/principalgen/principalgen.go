// Package principalgen writes the Go type of identity's Principal contract from its JSON Schema, so
// a field the contract adds reaches the adapter mechanically. It knows only the shapes the schema
// uses: strings (with an enum or as a date-time), booleans, arrays of strings, and objects of those.
package principalgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"sort"
	"strings"
)

type schema struct {
	Title       string                     `json:"title"`
	Description string                     `json:"description"`
	Type        string                     `json:"type"`
	Format      string                     `json:"format"`
	Enum        []string                   `json:"enum"`
	Items       *schema                    `json:"items"`
	Required    []string                   `json:"required"`
	Properties  map[string]json.RawMessage `json:"properties"`
	order       []string
}

// Generate is the Go source of package pkg's Principal type, from the schema's bytes.
func Generate(pkg string, raw []byte) ([]byte, error) {
	root, err := parse(raw)
	if err != nil {
		return nil, err
	}
	g := &generator{}
	if err := g.object(root.Title, root); err != nil {
		return nil, err
	}
	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by principalgen from the Principal contract's schema; DO NOT EDIT.\n\npackage %s\n\n", pkg)
	if g.usesTime {
		src.WriteString("import \"time\"\n\n")
	}
	src.Write(g.out.Bytes())
	return format.Source(src.Bytes())
}

func parse(raw []byte) (*schema, error) {
	var s schema
	if err := json.Unmarshal(raw, &s); err != nil {
		return nil, err
	}
	order, err := keyOrder(raw)
	if err != nil {
		return nil, err
	}
	s.order = order
	return &s, nil
}

// keyOrder is the order a schema's properties are written in, which map decoding loses.
func keyOrder(raw []byte) ([]string, error) {
	var top map[string]json.RawMessage
	if err := json.Unmarshal(raw, &top); err != nil {
		return nil, err
	}
	props, ok := top["properties"]
	if !ok {
		return nil, nil
	}
	dec := json.NewDecoder(bytes.NewReader(props))
	if _, err := dec.Token(); err != nil {
		return nil, err
	}
	var keys []string
	for dec.More() {
		key, err := dec.Token()
		if err != nil {
			return nil, err
		}
		keys = append(keys, key.(string))
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return nil, err
		}
	}
	return keys, nil
}

type generator struct {
	out      bytes.Buffer
	usesTime bool
}

func (g *generator) object(name string, s *schema) error {
	var fields bytes.Buffer
	var nested []func() error
	for _, prop := range s.order {
		p, err := parse(s.Properties[prop])
		if err != nil {
			return err
		}
		goName := exported(prop)
		required := slices.Contains(s.Required, prop)
		typ, err := g.typeOf(name, goName, p, required, &nested)
		if err != nil {
			return fmt.Errorf("%s: %w", prop, err)
		}
		tag := prop
		if !required {
			tag += ",omitempty"
		}
		comment(&fields, goName, p.Description)
		fmt.Fprintf(&fields, "\t%s %s `json:%q`\n", goName, typ, tag)
	}
	comment(&g.out, name, s.Description)
	fmt.Fprintf(&g.out, "type %s struct {\n%s}\n\n", name, fields.String())
	for _, write := range nested {
		if err := write(); err != nil {
			return err
		}
	}
	return nil
}

func (g *generator) typeOf(owner, goName string, p *schema, required bool, nested *[]func() error) (string, error) {
	switch {
	case len(p.Enum) > 0:
		g.enum(goName, p)
		return goName, nil
	case p.Type == "string" && p.Format == "date-time":
		g.usesTime = true
		if required {
			return "time.Time", nil
		}
		return "*time.Time", nil
	case p.Type == "string":
		return "string", nil
	case p.Type == "boolean":
		return "bool", nil
	case p.Type == "array" && p.Items != nil && p.Items.Type == "string":
		return "[]string", nil
	case p.Type == "object":
		*nested = append(*nested, func() error { return g.object(goName, p) })
		if required {
			return goName, nil
		}
		return "*" + goName, nil
	}
	return "", fmt.Errorf("principalgen: no Go type for %s.%s (type %q)", owner, goName, p.Type)
}

func (g *generator) enum(name string, p *schema) {
	comment(&g.out, name, p.Description)
	fmt.Fprintf(&g.out, "type %s string\n\nconst (\n", name)
	values := append([]string(nil), p.Enum...)
	sort.Strings(values)
	for _, v := range values {
		fmt.Fprintf(&g.out, "\t%s%s %s = %q\n", name, exported(v), name, v)
	}
	g.out.WriteString(")\n\n")
}

func comment(b *bytes.Buffer, name, description string) {
	if description == "" {
		return
	}
	text := description
	if !strings.HasPrefix(text, name+" ") {
		text = name + " is " + strings.ToLower(text[:1]) + text[1:]
	}
	for _, line := range wrap(text, 96) {
		fmt.Fprintf(b, "// %s\n", line)
	}
}

func wrap(text string, width int) []string {
	var lines []string
	line := ""
	for _, word := range strings.Fields(text) {
		if line != "" && len(line)+1+len(word) > width {
			lines = append(lines, line)
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += word
	}
	return append(lines, line)
}

// initialisms are the Go spellings of words that are initialisms.
var initialisms = map[string]string{"id": "ID", "sid": "SID"} //nolint:gochecknoglobals // a fixed table

// exported is a JSON name or enum value as an exported Go name: twoFactorAt is TwoFactorAt,
// personal-token is PersonalToken, sid is SID.
func exported(name string) string {
	if v, ok := initialisms[name]; ok {
		return v
	}
	var b strings.Builder
	upper := true
	for _, r := range name {
		if r == '-' || r == '_' {
			upper = true
			continue
		}
		if upper {
			b.WriteString(strings.ToUpper(string(r)))
			upper = false
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}
